#!/usr/bin/env node
/*
 * Bundle data/laws/*.json plus generated SVG into a classic script so the web
 * viewer works from file:// with no server and no build tooling.
 *
 * Output is deterministic: running twice produces identical bytes.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";
import { ROOT, loadCards, withCitation } from "./lib/deck.mjs";

const require = createRequire(import.meta.url);
const { renderSvg } = require("./svg.js");

const cards = await loadCards();
const bundled = cards.map((card) => ({
  ...withCitation(card),
  svg: renderSvg(card.graphicMetaphor)
}));

const out = join(ROOT, "packages", "web", "deck-data.js");
await mkdir(join(ROOT, "packages", "web"), { recursive: true });
const body =
  "/* Generated by scripts/generate-web-data.mjs. Do not edit by hand. */\n" +
  "window.UX_DECK = " +
  JSON.stringify({ deck: "UX & Behavioral Design", cards: bundled }, null, 2) +
  ";\n";
await writeFile(out, body);
console.log(`wrote packages/web/deck-data.js (${bundled.length} cards)`);
