#!/usr/bin/env node
/*
 * Bundle a deck's records plus generated SVG into a classic script so the web
 * viewer works from file:// with no server and no build tooling.
 *
 * One file per deck, under packages/web/decks/<slug>/: a second deck needs its
 * own bundle, and a shared filename would make the first deck a special case.
 * Output is deterministic: running twice produces identical bytes.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";
import { DECKS_DIR, ROOT, citationText, deckArgs, deckShape, loadCards, loadDecks, orderCards, resolveFromRoot, withCitation } from "../packages/core/deck.mjs";

const require = createRequire(import.meta.url);
const { renderSvg } = require("../packages/core/svg.js");

export function webDir(deck) {
  return resolveFromRoot(deck.web.dir || `packages/web/decks/${deck.slug}`);
}

const escapeHtml = (text) =>
  String(text).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

// The same citation line the card's own verso prints. packages/web/app.js
// holds the viewer's copy of this rule; check-web compares every index cell
// to the rendered card, so the two cannot drift silently.

// The complete card list as a table, so a reader can scan every id, name,
// family and source without opening fifty-four flip cards. It is generated
// from the same records and the same order as the grid; a deck that carries no
// attribution prints no Source column rather than a column of blanks.
const cardIndexMarkup = (deck, shape, cards) => {
  const groupKey = shape.fields.group;
  const groupWord = groupKey === "family" ? "Family" : "Category";
  const attribution = shape.fields.attribution;
  const head =
    `        <tr><th scope="col">ID</th><th scope="col">Card</th>` +
    `<th scope="col">${groupWord}</th>` +
    (attribution ? `<th scope="col">Source</th>` : "") +
    `</tr>`;
  const rows = cards.map((card) => {
    const source = attribution ? citationText(card[attribution]) : "";
    return (
      `        <tr>` +
      `<td class="index-id"><a href="#card-${escapeHtml(card.id)}">${escapeHtml(card.id)}</a></td>` +
      `<td class="index-name">${escapeHtml(card.name)}</td>` +
      `<td class="index-group">${escapeHtml(card[groupKey])}</td>` +
      (attribution ? `<td class="index-source">${escapeHtml(source)}</td>` : "") +
      `</tr>`
    );
  });
  return (
    `    <section class="card-index" aria-labelledby="card-index-title">\n` +
    `      <h2 id="card-index-title">All ${cards.length} cards</h2>\n` +
    `      <div class="card-index-scroll">\n` +
    `      <table>\n` +
    `        <thead>\n${head}\n        </thead>\n` +
    `        <tbody>\n${rows.join("\n")}\n        </tbody>\n` +
    `      </table>\n` +
    `      </div>\n` +
    `    </section>`
  );
};

const args = deckArgs();
const decks = await loadDecks(args);
const template = await readFile(join(ROOT, "packages", "web", "index.template.html"), "utf8");

for (const deck of decks) {
  // Same declared order as the printed pages, so the two cannot disagree.
  const shape = deckShape(deck);
  const cards = orderCards(deck, await loadCards(deck));
  const bundled = cards.map((card) => ({
    ...withCitation(card, deck),
    svg: renderSvg(shape.figure(card))
  }));

  // The keys every deck already had, in the same order, so a deck that
  // declares nothing new keeps its generated page byte for byte. A deck with
  // back-face blocks adds the four keys that describe them.
  const fields = {
    group: shape.fields.group,
    items: shape.fields.items,
    attribution: shape.fields.attribution,
    prompt: shape.fields.prompt,
    labelPrompt: shape.labelPrompt,
    labelItems: shape.labelCardItems,
    itemStyle: shape.itemStyle,
    // The line on the card's face that invites a flip. A deck whose back
    // is ordered beats rather than a checklist says so in its own words.
    backHint: deck.web.backHint || "Tap or press Enter to see the checklist"
  };
  if (shape.blocks.length > 0) {
    // The same face as the printed card: a block the deck keeps off the card
    // ("card": false) is not on the viewer's card either. It stays in the
    // rules and the skill, which have room for it.
    fields.blocks = shape.blocks.filter((block) => block.card !== false);
    fields.headline = shape.fields.headline;
    fields.context = shape.fields.context;
    fields.labelContext = shape.labelContext;
  }
  // A deck may print the source's own id on the card while the record keeps
  // its deck id. Added only when declared, so a deck that names none keeps
  // its generated page byte for byte.
  if (shape.cardId) fields.cardId = shape.cardId;

  const dir = webDir(deck);
  await mkdir(dir, { recursive: true });
  const body =
    "/* Generated by scripts/generate-web-data.mjs. Do not edit by hand. */\n" +
    `window.${deck.web.global} = ` +
    JSON.stringify({ deck: deck.name, cards: bundled }, null, 2) +
    ";\n";
  await writeFile(join(dir, "deck-data.js"), body);

  // The accents live in their own file so the bundle above keeps its bytes:
  // the deck-data.js of a shipped deck is a published artifact.
  const accents = Object.entries(deck.accents || {}).map(
    ([category, hex]) => `  ${JSON.stringify(category)}: ${JSON.stringify(hex.toLowerCase())}`
  );
  await writeFile(
    join(dir, "accents.js"),
    `/* Generated by scripts/generate-web-data.mjs. Do not edit by hand. */\n` +
      `window.${deck.web.accentsGlobal} = {\n${accents.join(",\n")}\n};\n`
  );

  const page = template
    .replaceAll("{{title}}", escapeHtml(deck.web.title))
    .replaceAll("{{heading}}", escapeHtml(deck.web.heading))
    .replaceAll("{{lede}}", escapeHtml(deck.web.lede))
    .replaceAll("{{source}}", deck.web.source)
    .replaceAll("{{global}}", deck.web.global)
    .replaceAll("{{accentsGlobal}}", deck.web.accentsGlobal)
    .replaceAll("{{cardIndex}}", () => cardIndexMarkup(deck, shape, bundled))
    .replaceAll("{{fields}}", JSON.stringify(fields));
  await writeFile(join(dir, "index.html"), page);

  console.log(`wrote packages/web/decks/${deck.slug}/ (deck-data.js, accents.js, index.html; ${bundled.length} cards)`);
}

/*
 * The repository's web entry point: one page listing every deck, so a reader
 * opening packages/web/index.html sees the platform rather than one deck's
 * viewer.
 *
 * Written only when the repository's own decks/ is being built in full. A test
 * that passes --decks-dir is building a deck somewhere else and must not
 * rewrite the real index (or, worse, list a scratch deck in it); a --deck run
 * leaves the index to the full build, so one deck's job cannot fail another's.
 */
if (args.dir === DECKS_DIR && !args.only) {
  const all = await loadDecks({ dir: args.dir });
  const rows = [];
  for (const deck of all) {
    const cards = await loadCards(deck);
    const groupWord = deckShape(deck).fields.group === "family" ? "families" : "categories";
    rows.push(
      `      <li class="deck-entry">\n` +
        `        <a class="deck-link" href="decks/${escapeHtml(deck.slug)}/index.html">\n` +
        `          <span class="deck-name">${escapeHtml(deck.name)}</span>\n` +
        `          <span class="deck-meta">${cards.length} cards · ${(deck.categories || []).length} ${groupWord}</span>\n` +
        `          <span class="deck-description">${escapeHtml(deck.description || "")}</span>\n` +
        `          <span class="deck-go">Open deck →</span>\n` +
        `        </a>\n` +
        `      </li>`
    );
  }
  const page = (await readFile(join(ROOT, "packages", "web", "deck-index.template.html"), "utf8"))
    .replaceAll("{{title}}", "Knowledge Domain Decks")
    .replaceAll("{{heading}}", "Knowledge Domain Decks")
    .replaceAll(
      "{{lede}}",
      `${all.length} reference card decks. Every card is a validated record; ` +
        `each deck builds a print PDF, this phone viewer, and an agent ruleset from the same data.`
    )
    .replaceAll("{{decks}}", rows.join("\n"))
    .replaceAll("{{source}}", "Generated from <code>decks/*/deck.json</code>. Code MIT · data CC0-1.0.");
  await writeFile(join(ROOT, "packages", "web", "index.html"), page);
  console.log(`wrote packages/web/index.html (${all.length} decks)`);
}
