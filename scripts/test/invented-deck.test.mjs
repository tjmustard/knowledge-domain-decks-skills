/*
 * The engine is deck-agnostic, proved by building a deck it has never seen.
 *
 * This deck is invented here, in a scratch directory, and never committed: it
 * is not under decks/, so nothing in the repository knows it exists. It goes
 * through validate, the rules generator, the web generator and Typst using the
 * same code paths the shipped deck uses.
 *
 * That is the whole claim of the restructure. A layout that merely moved files
 * would still build one deck; an engine that can build a second one without an
 * edit under packages/ is what makes the next slice possible. If this test
 * needs a change in packages/ to pass, the engine is not there yet.
 */
import test from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

const runNode = (script, args) => {
  const result = spawnSync(process.execPath, [script, ...args], {
    cwd: ROOT,
    encoding: "utf8",
    timeout: 300_000
  });
  return {
    status: result.status,
    output: `${result.stdout || ""}\n${result.stderr || ""}`.trim()
  };
};

const typst = spawnSync("typst", ["--version"], { encoding: "utf8" });
const hasTypst = !typst.error && typst.status === 0;

async function makeDeck(dir) {
  const deckDir = join(dir, "decks", "invented");
  await mkdir(join(deckDir, "data", "laws"), { recursive: true });

  // The schema is the one a real deck ships; a synthetic record that only
  // passes a laxer schema would prove nothing about the deck gate.
  await writeFile(
    join(deckDir, "data", "law-schema.json"),
    await readFile(join(ROOT, "decks", "ux-laws", "data", "law-schema.json"), "utf8")
  );
  await writeFile(
    join(deckDir, "data", "laws", "inv-01.json"),
    JSON.stringify(
      {
        id: "INV-01",
        name: "The Invented Principle",
        category: "Invented Category",
        axiom: "A synthetic card proves the engine builds a deck it has never seen.",
        trigger: "Used only by the deck-agnostic test in this repository.",
        checklist: [
          { text: "Build it through the same pipeline as a real deck.", kind: "code" },
          { text: "Read every path from deck.json rather than from the source.", kind: "code" },
          { text: "Say so plainly if a step could not run here.", kind: "research" }
        ],
        antiPattern: {
          violation: "An engine that needs an edit per deck.",
          remediation: "Read the deck from deck.json and build it."
        },
        academicOrigin: {
          authors: ["Ada Lovelace", "Alan Turing"],
          year: 1843,
          title: "Notes on the Analytical Engine",
          publication: "Taylor's Scientific Memoirs"
        },
        graphicMetaphor: {
          svgShape: "proximity-grid",
          parametricParams: { columns: 3, rows: 2, intraGap: 36, interGap: 96 }
        }
      },
      null,
      2
    ) + "\n"
  );

  const deck = {
    id: "invented",
    slug: "invented",
    name: "Invented Deck",
    description: "A deck that exists only inside this test.",
    categories: ["Invented Category"],
    accents: { "Invented Category": "#123456" },
    outputs: {
      rules: join(dir, "out", "invented-rules.md"),
      skill: join(dir, "out", "skills", "invented"),
      pdf: join(dir, "out", "invented.pdf")
    },
    rules: {
      title: "Invented Rules",
      intro: "Rules from a deck that does not ship."
    },
    skill: {
      name: "invented",
      description: "A synthetic deck with {cards} card.",
      title: "Invented",
      intro: "The index.",
      commonRules: ["Read the card."],
      footer: "End of the invented deck."
    },
    web: {
      global: "INVENTED_DECK",
      accentsGlobal: "INVENTED_DECK_ACCENTS",
      title: "Invented Deck",
      heading: "Invented Deck",
      lede: "Built by a test.",
      source: "Generated by a test.",
      dir: join(dir, "out", "web")
    }
  };
  await writeFile(join(deckDir, "deck.json"), JSON.stringify(deck, null, 2) + "\n");
  return join(dir, "decks");
}

test("a deck the repository has never seen builds through the same pipeline", async (t) => {
  const dir = await mkdtemp(join(tmpdir(), "kdd-invented-"));
  try {
    const decksDir = await makeDeck(dir);
    const args = ["--decks-dir", decksDir];

    const validated = runNode("scripts/validate.mjs", args);
    assert.equal(validated.status, 0, validated.output);
    assert.match(validated.output, /OK: 1 record\(s\) valid/);

    const rules = runNode("packages/rules/generate.mjs", args);
    assert.equal(rules.status, 0, rules.output);
    const rulesText = await readFile(join(dir, "out", "invented-rules.md"), "utf8");
    assert.match(rulesText, /^# Invented Rules$/m);
    assert.match(rulesText, /### INV-01 — The Invented Principle/);
    assert.match(rulesText, /Ada Lovelace & Alan Turing \(1843\)/);
    const skillText = await readFile(join(dir, "out", "skills", "invented", "SKILL.md"), "utf8");
    assert.match(skillText, /^name: invented$/m);
    // The {cards} placeholder is filled by the engine, not the deck author.
    assert.match(skillText, /synthetic deck with 1 card\./);

    const web = runNode("scripts/generate-web-data.mjs", args);
    assert.equal(web.status, 0, web.output);
    const bundle = await readFile(join(dir, "out", "web", "deck-data.js"), "utf8");
    assert.match(bundle, /window\.INVENTED_DECK = /);
    assert.equal((bundle.match(/"id":/g) || []).length, 1);
    const page = await readFile(join(dir, "out", "web", "index.html"), "utf8");
    assert.match(page, /<h1>Invented Deck<\/h1>/);
    assert.match(page, /window\.DECK_GLOBAL = "INVENTED_DECK"/);

    if (!hasTypst) {
      t.diagnostic("Typst is absent, so the print half of this deck was not built");
      return;
    }
    const printed = runNode("packages/prepress/build.mjs", args);
    assert.equal(printed.status, 0, printed.output);
    assert.ok(existsSync(join(dir, "out", "invented.pdf")), "no PDF was written");

    const checked = runNode("scripts/pdf-check.mjs", [
      ...args,
      "--deck",
      "invented",
      "--expect-pages",
      "2"
    ]);
    assert.equal(checked.status, 0, checked.output);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});
