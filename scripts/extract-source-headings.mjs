/*
 * Extract the archetype deck's sixteen card headings from the research input.
 *
 * The deck's test holds its records to an extraction of the source rather than
 * to a retyped list. The research input is read-only and not in git (see
 * .gitignore: provenance and licence are the person's call), so a checkout -
 * CI included - cannot read it. This script writes what it read to
 * decks/archetypes/data/source-headings.json, the deck's own data tree; the
 * test compares records against that file, and where the input is present it
 * re-extracts and holds the committed file to it.
 *
 * Usage: node scripts/extract-source-headings.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(import.meta.dirname, "..");
const SOURCE_REL = "03 - Archetypes/Archetype Card Deck Framework.md";
const SOURCE = join(ROOT, "SupportingInformation", SOURCE_REL);
const OUT = join(ROOT, "decks", "archetypes", "data", "source-headings.json");

// One card, one heading: `### **Card 07: The Everyperson**`. A fresh regex per
// call, so a caller cannot leave lastIndex set for the next one.
export const extractHeadings = (text) =>
  [...text.matchAll(/^### \*\*Card (\d{2}): The (.+?)\*\*$/gm)].map((match) => ({
    number: Number(match[1]),
    name: match[2]
  }));

const main = async () => {
  const text = await readFile(SOURCE, "utf8");
  const headings = extractHeadings(text);
  if (headings.length !== 16) {
    throw new Error(`expected 16 card headings in ${SOURCE_REL}, found ${headings.length}`);
  }
  const artifact = {
    $comment:
      "Generated by scripts/extract-source-headings.mjs from the read-only research input, which is not in git. Do not edit by hand: rerun the script.",
    source: SOURCE_REL,
    sourceSha256: createHash("sha256").update(text).digest("hex"),
    headings
  };
  await writeFile(OUT, JSON.stringify(artifact, null, 2) + "\n");
  console.log(`wrote ${headings.length} headings to ${OUT}`);
};

const invokedDirectly =
  process.argv[1] && join(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  await main();
}
