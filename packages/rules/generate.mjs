#!/usr/bin/env node
/*
 * Compile a deck's records into its agent-facing artifacts:
 *   rules/<name>.md                       every card, as rules to paste
 *   skills/<slug>/SKILL.md                an index an agent loads first
 *   skills/<slug>/resources/<category>.md one file per category, read on demand
 *
 * All are pure functions of the deck's data/laws/*.json, so regeneration is
 * byte-identical. The skill is split because a skill file is loaded whole: at
 * thirty-four cards it was 28 KB before an agent had read a line of the code it
 * was auditing. The index carries what decides which file to open; the bodies
 * carry the checks.
 *
 * Every literal that differs between decks - the titles, the prose, the skill
 * name, the output paths - comes out of deck.json. Nothing here knows which
 * deck it is building, which is what lets the second deck exist.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { deckArgs, deckShape, loadCards, loadDecks, resolveFromRoot, sourceLine, sourceShort, withCitation } from "../core/deck.mjs";

// The provenance line is deliberately deck-neutral in its wording but names
// the old data/ path: changing it would change the bytes of a shipped
// artifact, which this slice forbids. It is one line of cosmetic debt, carried
// until a content change is authorized.
const GENERATED = "<!-- Generated by packages/rules/generate.mjs from data/laws/*.json. Do not edit by hand. -->";

function lines(text) {
  return String(text).split("\n");
}

// How one declared block reads as a sentence, for the artifacts that present a
// card's fields as prose rather than as a face. Returns the lines to push.
function blockLines(block, value) {
  if (value === undefined || value === null || value === "") return [];
  if (Array.isArray(value)) {
    if (value.length === 0) return [];
    if (block.style === "list") {
      return [
        `**${block.label}.**`,
        ...value.map((entry) => `- ${entry}`)
      ];
    }
    const join = block.style === "quotes" ? " " : " · ";
    return [`**${block.label}.** ${value.join(join)}`];
  }
  // A labelled block is the record's own { label, text } pair, printed as the
  // two things it is: the name of the move, then the words of it.
  if (typeof value === "object" && value.label && value.text) {
    return [`**${block.label}.** ${value.label}`, "", value.text];
  }
  return [`**${block.label}.** ${value}`];
}

// The card's own words for its two front lines, under the deck's own headings.
// A block deck names these fields in deck.json; a deck that does not has no
// block list, so this never runs for the decks that shipped before it.
function frontLines(shape, card) {
  const out = [];
  const headline = shape.fields.headline;
  if (headline && card[headline]) out.push(`**${shape.labelHeadline || "Headline"}.** ${card[headline]}`, "");
  const context = shape.fields.context;
  if (context && card[context]) out.push(`**${shape.labelContext}.** ${card[context]}`, "");
  return out;
}

function rulesMarkdown(deck, shape, grouped) {
  const out = [`# ${deck.rules.title}`, "", GENERATED, "", ...lines(deck.rules.intro), ""];
  const blocks = shape.blocks.length > 0;
  for (const [category, items] of grouped) {
    if (items.length === 0) continue;
    out.push(`## ${category}`, "");
    for (const card of items) {
      out.push(`### ${card.id} — ${card.name}`, "");
      if (blocks) {
        out.push(...frontLines(shape, card));
        // A deck can declare back-face blocks and still carry ordered items:
        // the facilitation deck prints steps, failure, fix and provenance. The
        // block branch used to skip the items, which silently dropped the run
        // sheet from the rules file. A deck with no items field adds nothing.
        if (shape.fields.items) {
          const cardItems = shape.items(card);
          if (cardItems.length > 0) {
            out.push(`**${shape.labelItems}.**`);
            if (shape.itemStyle === "steps") {
              cardItems.forEach((item, index) => out.push(`${index + 1}. ${checklistLine(item)}`));
            } else {
              for (const item of cardItems) out.push(`- [ ] ${checklistLine(item)}`);
            }
            out.push("");
          }
        }
        for (const block of shape.blocks) out.push(...blockLines(block, card[block.field]), "");
        const source = sourceLine(shape.attribution(card));
        if (source) out.push(`**Source.** ${source}`, "");
        continue;
      }
      out.push(`**Axiom.** ${card.axiom}`, "");
      out.push(`**Apply when.** ${card.trigger}`, "");
      out.push(`**${shape.labelItems}.**`);
      for (const item of shape.items(card)) out.push(`- [ ] ${checklistLine(item)}`);
      out.push("");
      out.push(`**Anti-pattern.** ${card.antiPattern.violation}`, "");
      out.push(`**Fix.** ${card.antiPattern.remediation}`, "");
      out.push(`**Source.** ${sourceLine(shape.attribution(card))}`, "");
    }
  }
  return out.join("\n");
}

// "Some & Thing" -> "some-thing". The ampersand is a separator, not a word:
// dropping it outright would give "something".
function categorySlug(category) {
  return category
    .toLowerCase()
    .replace(/&/g, " ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function skillMarkdown(deck, shape, grouped, cardCount) {
  const description = deck.skill.description.replace(/\{cards\}/g, String(cardCount));
  // A block deck's card is indexed by the line its front prints under the
  // deck's own heading; the shipped decks keep the words they always had.
  const blocks = shape.blocks.length > 0;
  const contextHeader = blocks ? shape.labelContext : "Apply when";
  const contextOf = (card) => (blocks ? card[shape.fields.context] : card.trigger);
  const out = [
    "---",
    `name: ${deck.skill.name}`,
    `description: ${description}`,
    "---",
    "",
    GENERATED,
    "",
    `# ${deck.skill.title}`,
    "",
    ...lines(deck.skill.intro),
    "",
    "Rules that hold across every card:",
    ""
  ];
  for (const rule of deck.skill.commonRules) {
    out.push(...lines(rule).map((line, i) => (i === 0 ? `- ${line}` : line)));
  }
  out.push("");
  for (const [category, items] of grouped) {
    if (items.length === 0) continue;
    const slug = categorySlug(category);
    out.push(`## ${category} (${items.length} ${items.length === 1 ? "card" : "cards"})`, "");
    out.push(
      blocks
        ? `Read \`resources/${slug}.md\` for the full card text.`
        : `Read \`resources/${slug}.md\` for the checks, fixes and sources.`,
      ""
    );
    out.push(`| ID | Card | ${contextHeader} |`);
    out.push("|---|---|---|");
    for (const card of items) {
      out.push(`| ${card.id} | ${card.name} | ${oneLine(contextOf(card) || "")} |`);
    }
    out.push("");
  }
  out.push(deck.skill.footer);
  out.push("");
  return out.join("\n");
}

function resourceMarkdown(category, shape, items) {
  const blocks = shape.blocks.length > 0;
  const out = [
    `# ${category}`,
    "",
    GENERATED,
    "",
    blocks
      ? `${items.length} card(s). Read each one that applies in full.`
      : `${items.length} card(s). Check the code in front of you against each one that applies.`,
    ""
  ];
  for (const card of items) {
    out.push(`## ${card.id} — ${card.name}`, "");
    if (blocks) {
      const headline = shape.fields.headline;
      if (headline && card[headline]) {
        out.push(`- **${shape.labelHeadline || "Headline"}:** ${card[headline]}`);
      }
      const context = shape.fields.context;
      if (context && card[context]) out.push(`- **${shape.labelContext}:** ${card[context]}`);
      // The same rule as the rules file: a block deck that declares items
      // prints them, in order, under the deck's own label.
      if (shape.fields.items) {
        const cardItems = shape.items(card);
        if (cardItems.length > 0) {
          out.push(`- **${shape.labelResourceItems}:**`);
          for (const item of cardItems) out.push(`  - ${checklistLine(item)}`);
        }
      }
      for (const block of shape.blocks) {
        const value = card[block.field];
        if (value === undefined || value === null || value === "") continue;
        if (Array.isArray(value)) {
          if (value.length === 0) continue;
          if (block.style === "list") {
            out.push(`- **${block.label}:**`);
            for (const entry of value) out.push(`  - ${entry}`);
          } else {
            out.push(`- **${block.label}:** ${value.join(block.style === "quotes" ? " " : " · ")}`);
          }
        } else {
          out.push(`- **${block.label}:** ${value}`);
        }
      }
      const source = sourceShort(shape.attribution(card));
      if (source) out.push(`- **Source:** ${source}`);
      out.push("");
      continue;
    }
    out.push(`- **Axiom:** ${card.axiom}`);
    out.push(`- **Apply when:** ${card.trigger}`);
    out.push(`- **${shape.labelResourceItems}:**`);
    for (const item of shape.items(card)) out.push(`  - ${checklistLine(item)}`);
    out.push(`- **Instead of:** ${card.antiPattern.violation}`);
    out.push(`- **Do:** ${card.antiPattern.remediation}`);
    out.push(`- **Source:** ${sourceShort(shape.attribution(card))}`);
    out.push("");
  }
  return out.join("\n");
}

// A research item is one an agent reading code cannot complete: it needs an
// experiment or a recorded run. Saying so in the generated artifact is the
// difference between an agent reporting the gap and an agent claiming a check
// it never made.
function checklistLine(item) {
  return item.kind === "research"
    ? `${item.text} _(research: an experiment or a recorded run; not checkable from code)_`
    : item.text;
}

// A trigger is one sentence in the record; a table cell cannot hold a line
// break, and a stray pipe would split the row.
function oneLine(text) {
  return String(text).replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();
}

async function generateDeck(deck) {
  const shape = deckShape(deck);
  const cards = (await loadCards(deck)).map((card) => withCitation(card, deck));
  const grouped = new Map(deck.categories.map((category) => [category, []]));
  for (const card of cards) {
    const key = shape.group(card);
    if (!grouped.has(key)) grouped.set(key, []);
    grouped.get(key).push(card);
  }

  const rulesFile = resolveFromRoot(deck.outputs.rules);
  const skillDir = resolveFromRoot(deck.outputs.skill);
  await mkdir(dirname(rulesFile), { recursive: true });
  await mkdir(join(skillDir, "resources"), { recursive: true });
  await writeFile(rulesFile, rulesMarkdown(deck, shape, grouped));
  await writeFile(join(skillDir, "SKILL.md"), skillMarkdown(deck, shape, grouped, cards.length));

  const written = [];
  for (const [category, items] of grouped) {
    if (items.length === 0) continue;
    const slug = categorySlug(category);
    await writeFile(join(skillDir, "resources", `${slug}.md`), resourceMarkdown(category, shape, items));
    written.push(`${deck.outputs.skill}/resources/${slug}.md`);
  }
  console.log(
    `${deck.slug}: wrote ${deck.outputs.rules}, ${deck.outputs.skill}/SKILL.md and ${written.length} resource file(s)`
  );
}

const decks = await loadDecks(deckArgs());
for (const deck of decks) await generateDeck(deck);
