#!/usr/bin/env node
/*
 * Compile the card dataset into the agent-facing artifacts:
 *   rules/ux-rules.md                       every card, as rules to paste
 *   skills/ux-laws/SKILL.md                 an index an agent loads first
 *   skills/ux-laws/resources/<category>.md   one file per category, read on demand
 *
 * All are pure functions of data/laws/*.json, so regeneration is byte-identical.
 * The skill is split because a skill file is loaded whole: at thirty-four cards
 * it was 28 KB before an agent had read a line of the code it was auditing. The
 * index carries what decides which file to open; the bodies carry the checks.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import {
  ROOT,
  CATEGORY_ORDER,
  loadCards,
  withCitation
} from "../../scripts/lib/deck.mjs";

const cards = (await loadCards()).map(withCitation);
const grouped = new Map(CATEGORY_ORDER.map((category) => [category, []]));
for (const card of cards) {
  if (!grouped.has(card.category)) grouped.set(card.category, []);
  grouped.get(card.category).push(card);
}

function rulesMarkdown() {
  const lines = [
    "# UX & Behavioral Design Rules",
    "",
    "<!-- Generated by packages/rules/generate.mjs from data/laws/*.json. Do not edit by hand. -->",
    "",
    "Apply these rules when reviewing or writing interface code. Each card names one",
    "public-domain principle, when to check for it, and the concrete fix.",
    ""
  ];
  for (const [category, items] of grouped) {
    if (items.length === 0) continue;
    lines.push(`## ${category}`, "");
    for (const card of items) {
      lines.push(`### ${card.id} — ${card.name}`, "");
      lines.push(`**Axiom.** ${card.axiom}`, "");
      lines.push(`**Apply when.** ${card.trigger}`, "");
      lines.push("**Checklist.**");
      for (const item of card.checklist) lines.push(`- [ ] ${item}`);
      lines.push("");
      lines.push(`**Anti-pattern.** ${card.antiPattern.violation}`, "");
      lines.push(`**Fix.** ${card.antiPattern.remediation}`, "");
      lines.push(
        `**Source.** ${card.academicOrigin.authorsLabel} (${card.academicOrigin.year}). *${card.academicOrigin.title}*${card.academicOrigin.titleStop} ${card.academicOrigin.publication}.`,
        ""
      );
    }
  }
  return lines.join("\n");
}

// "Heuristic & Mental Models" -> "heuristic-mental-models". The ampersand is
// a separator, not a word: dropping it outright would give "heuristic-mental".
function categorySlug(category) {
  return category
    .toLowerCase()
    .replace(/&/g, " ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function skillMarkdown() {
  const lines = [
    "---",
    "name: ux-laws",
    `description: Review or write interface code against the UX & Behavioral Design deck — ${cards.length} public-domain principles. Use when auditing layouts, forms, navigation, or touch targets. Start with the index below, then read the one resource file for the area you are checking.`,
    "---",
    "",
    "<!-- Generated by packages/rules/generate.mjs from data/laws/*.json. Do not edit by hand. -->",
    "",
    "# UX & Behavioral Design",
    "",
    "This file is the index. The cards themselves live in `resources/`, one",
    "file per category. Use the tables below to decide which file to open, then",
    "read that file. Do not load every resource unless the change spans several",
    "categories.",
    "",
    "Rules that hold across every card:",
    "",
    "- Prefer the smallest change that removes the failure state.",
    "- Check the code in front of you; do not restyle unrelated code.",
    "- A checklist item that asks for a human-subject experiment cannot be",
    "  satisfied by reading code. Say so rather than claiming it was done.",
    ""
  ];
  for (const [category, items] of grouped) {
    if (items.length === 0) continue;
    const slug = categorySlug(category);
    lines.push(`## ${category} (${items.length} ${items.length === 1 ? "card" : "cards"})`, "");
    lines.push(`Read \`resources/${slug}.md\` for the checks, fixes and sources.`, "");
    lines.push("| ID | Card | Apply when |");
    lines.push("|---|---|---|");
    for (const card of items) {
      lines.push(`| ${card.id} | ${card.name} | ${oneLine(card.trigger)} |`);
    }
    lines.push("");
  }
  lines.push("Every card cites one primary paper; the citation travels with the card.");
  lines.push("");
  return lines.join("\n");
}

function resourceMarkdown(category, items) {
  const lines = [
    `# ${category}`,
    "",
    "<!-- Generated by packages/rules/generate.mjs from data/laws/*.json. Do not edit by hand. -->",
    "",
    `${items.length} card(s). Check the code in front of you against each one that applies.`,
    ""
  ];
  for (const card of items) {
    lines.push(`## ${card.id} — ${card.name}`, "");
    lines.push(`- **Axiom:** ${card.axiom}`);
    lines.push(`- **Apply when:** ${card.trigger}`);
    lines.push(`- **Check:**`);
    for (const item of card.checklist) lines.push(`  - ${item}`);
    lines.push(`- **Instead of:** ${card.antiPattern.violation}`);
    lines.push(`- **Do:** ${card.antiPattern.remediation}`);
    lines.push(
      `- **Source:** ${card.academicOrigin.authorsLabel} (${card.academicOrigin.year}), *${card.academicOrigin.title}*${card.academicOrigin.titleStop}`
    );
    lines.push("");
  }
  return lines.join("\n");
}

// A trigger is one sentence in the record; a table cell cannot hold a line
// break, and a stray pipe would split the row.
function oneLine(text) {
  return String(text).replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();
}

await mkdir(join(ROOT, "rules"), { recursive: true });
await mkdir(join(ROOT, "skills", "ux-laws", "resources"), { recursive: true });
await writeFile(join(ROOT, "rules", "ux-rules.md"), rulesMarkdown());
await writeFile(join(ROOT, "skills", "ux-laws", "SKILL.md"), skillMarkdown());

const written = [];
for (const [category, items] of grouped) {
  if (items.length === 0) continue;
  const file = join(ROOT, "skills", "ux-laws", "resources", `${categorySlug(category)}.md`);
  await writeFile(file, resourceMarkdown(category, items));
  written.push(`skills/ux-laws/resources/${categorySlug(category)}.md`);
}
console.log(`wrote rules/ux-rules.md, skills/ux-laws/SKILL.md and ${written.length} resource file(s)`);
