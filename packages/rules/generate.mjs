#!/usr/bin/env node
/*
 * Compile the card dataset into two agent-facing artifacts:
 *   rules/ux-rules.md
 *   skills/ux-laws/SKILL.md
 *
 * Both are pure functions of data/laws/*.json, so regeneration is byte-identical.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import {
  ROOT,
  CATEGORY_ORDER,
  loadCards,
  withCitation
} from "../../scripts/lib/deck.mjs";

const cards = (await loadCards()).map(withCitation);
const grouped = new Map(CATEGORY_ORDER.map((category) => [category, []]));
for (const card of cards) {
  if (!grouped.has(card.category)) grouped.set(card.category, []);
  grouped.get(card.category).push(card);
}

function rulesMarkdown() {
  const lines = [
    "# UX & Behavioral Design Rules",
    "",
    "<!-- Generated by packages/rules/generate.mjs from data/laws/*.json. Do not edit by hand. -->",
    "",
    "Apply these rules when reviewing or writing interface code. Each card names one",
    "public-domain principle, when to check for it, and the concrete fix.",
    ""
  ];
  for (const [category, items] of grouped) {
    if (items.length === 0) continue;
    lines.push(`## ${category}`, "");
    for (const card of items) {
      lines.push(`### ${card.id} — ${card.name}`, "");
      lines.push(`**Axiom.** ${card.axiom}`, "");
      lines.push(`**Apply when.** ${card.trigger}`, "");
      lines.push("**Checklist.**");
      for (const item of card.checklist) lines.push(`- [ ] ${item}`);
      lines.push("");
      lines.push(`**Anti-pattern.** ${card.antiPattern.violation}`, "");
      lines.push(`**Fix.** ${card.antiPattern.remediation}`, "");
      lines.push(
        `**Source.** ${card.academicOrigin.authorsLabel} (${card.academicOrigin.year}). *${card.academicOrigin.title}*${card.academicOrigin.titleStop} ${card.academicOrigin.publication}.`,
        ""
      );
    }
  }
  return lines.join("\n");
}

function skillMarkdown() {
  const lines = [
    "---",
    "name: ux-laws",
    `description: Review or write interface code against the UX & Behavioral Design deck — ${cards.length} public-domain principles with triggers, checklists, and remediations. Use when auditing layouts, forms, navigation, touch targets, or long lists.`,
    "---",
    "",
    "<!-- Generated by packages/rules/generate.mjs from data/laws/*.json. Do not edit by hand. -->",
    "",
    "# UX & Behavioral Design",
    "",
    "Check the code in front of you against each applicable card. Prefer the",
    "smallest change that removes the failure state; do not restyle unrelated code.",
    ""
  ];
  for (const [category, items] of grouped) {
    if (items.length === 0) continue;
    lines.push(`## ${category}`, "");
    for (const card of items) {
      lines.push(`### ${card.id} — ${card.name}`, "");
      lines.push(`- **Axiom:** ${card.axiom}`);
      lines.push(`- **Apply when:** ${card.trigger}`);
      lines.push(`- **Check:**`);
      for (const item of card.checklist) lines.push(`  - ${item}`);
      lines.push(`- **Instead of:** ${card.antiPattern.violation}`);
      lines.push(`- **Do:** ${card.antiPattern.remediation}`);
      lines.push(
        `- **Source:** ${card.academicOrigin.authorsLabel} (${card.academicOrigin.year}), *${card.academicOrigin.title}*${card.academicOrigin.titleStop}`
      );
      lines.push("");
    }
  }
  return lines.join("\n");
}

await mkdir(join(ROOT, "rules"), { recursive: true });
await mkdir(join(ROOT, "skills", "ux-laws"), { recursive: true });
await writeFile(join(ROOT, "rules", "ux-rules.md"), rulesMarkdown());
await writeFile(join(ROOT, "skills", "ux-laws", "SKILL.md"), skillMarkdown());
console.log("wrote rules/ux-rules.md and skills/ux-laws/SKILL.md");
